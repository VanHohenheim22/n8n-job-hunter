#!/usr/bin/env node
// Genera n8n/workflows/wf2-filtro-avisos.json:
//   cada hora → clasificar por reglas (n8n/sql/classify_offers.sql) → candidatas sin avisar
//   → mensajes de Telegram (uno por oferta, o resumen si hay muchas) → marcar notified_at.
// Lee TELEGRAM_CHAT_ID de infra/.env. Uso: node scripts/build_wf2.js && scripts/n8n.sh push n8n/workflows/wf2-filtro-avisos.json
'use strict';
const { read, COLOR, sticky, doc, connector, writeWorkflow } = require('./lib/wf');
const env = Object.fromEntries(read('infra/.env').split('\n')
  .map((l) => l.match(/^([A-Z0-9_]+)=([^#\s]*)/)).filter(Boolean).map((m) => [m[1], m[2]]));
const CHAT_ID = env.TELEGRAM_CHAT_ID;
if (!CHAT_ID) throw new Error('Falta TELEGRAM_CHAT_ID en infra/.env');

const PG = { postgres: { id: 'jhPgJobs00000001', name: 'Postgres jobs' } };
const TG = { telegramApi: { id: '0oBvnvYgYSOOhmhG', name: 'Telegram Empliosbot' } };
const MAX_INDIVIDUAL = 8; // más candidatas que esto → un solo mensaje resumen
const DIGEST_TOP = 12;

const pendingSql = `SELECT id, title, company, location, salary_min, salary_max, url, source, score, reasons, lang, job_type,
       published_at
FROM offers WHERE status = 'candidate' AND notified_at IS NULL
ORDER BY score DESC, published_at DESC NULLS LAST LIMIT 300;`;

const markSql = `UPDATE offers SET notified_at = now()
WHERE id IN (SELECT jsonb_array_elements_text($1::jsonb)::bigint)
RETURNING id;`;

// Código del nodo de formato (se ejecuta en n8n). Escapa HTML: títulos y empresas son contenido externo.
const formatCode = `// GENERATED by scripts/build_wf2.js — do not edit here. External text is HTML-escaped.
const MAX_INDIVIDUAL = ${MAX_INDIVIDUAL}, DIGEST_TOP = ${DIGEST_TOP};
const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const safeUrl = (u) => /^https?:\\/\\//i.test(String(u || '')) ? esc(u) : '';
const money = (o) => o.salary_min ? \`💰 $\${Math.round(o.salary_min / 1000)}k\${o.salary_max && o.salary_max !== o.salary_min ? '–' + Math.round(o.salary_max / 1000) + 'k' : ''} USD/año\` : '';
const flag = (o) => (o.reasons || []).includes('pide inglés') || o.lang === 'en' ? '🇬🇧' : '🇪🇸';
const link = (o, label) => safeUrl(o.url) ? \`<a href="\${safeUrl(o.url)}">\${esc(label)}</a>\` : esc(label);

const offers = $input.all().map((i) => i.json).filter((o) => o && o.id);
if (offers.length === 0) return [];

if (offers.length <= MAX_INDIVIDUAL) {
  return offers.map((o) => ({ json: { ids: [o.id], text: [
    \`⭐ <b>\${o.score}</b> \${flag(o)} \${link(o, o.title)}\`,
    [o.company && \`🏢 \${esc(o.company)}\`, o.location && \`📍 \${esc(o.location)}\`].filter(Boolean).join(' · '),
    [money(o), o.job_type && \`⏱ \${esc(o.job_type)}\`].filter(Boolean).join(' · '),
    \`🏷 \${esc((o.reasons || []).join(', '))}\`,
    \`<i>\${esc(o.source)}</i>\`,
  ].filter(Boolean).join('\\n') } }));
}

const top = offers.slice(0, DIGEST_TOP).map((o, n) =>
  \`\${n + 1}. ⭐\${o.score} \${flag(o)} \${link(o, o.title)}\${o.company ? ' — ' + esc(o.company) : ''}\${money(o) ? ' · ' + money(o) : ''}\`);
const rest = offers.length - DIGEST_TOP;
return [{ json: { ids: offers.map((o) => o.id), text: [
  \`📋 <b>\${offers.length} ofertas nuevas</b> que encajan contigo. Las mejores:\`, '', ...top,
  rest > 0 ? \`\\n…y \${rest} más (status = 'candidate' en la base jobs).\` : '',
].join('\\n') } }];
`;

const N = {
  cron: 'Every hour', manual: 'Run manually', classify: 'Classify with rules', pending: 'Get pending candidates',
  format: 'Format messages', send: 'Send to Telegram', mark: 'Mark as notified',
};
const Y = 360, X = [0, 260, 520, 780, 1040, 1300];

const nodes = [
  sticky('header', [
    '## WF2 · Filter offers & notify on Telegram',
    'Every hour: deterministic **SQL rules** score new offers (stack, region, seniority, language, age) and store',
    'the **reasons**. Candidates not yet notified go to Telegram: one message each, or a digest if there are more than ' + MAX_INDIVIDUAL + '.',
    '',
    '⚙️ Generated by `scripts/build_wf2.js` · rules in `n8n/sql/classify_offers.sql` — **do not edit here**.',
  ].join('\n'), [-60, 0], [1580, 200], COLOR.header),
  sticky('rules', '### 1 · Score (no AI)\nstatus → candidate | filtered_out\nNothing is deleted', [X[1] - 60, 240], [480, 320], COLOR.transform),
  sticky('notify', '### 2 · Notify\nTitles/companies are untrusted\n→ escaped before sending', [X[3] - 60, 240], [480, 320], COLOR.output),
  sticky('mark', '### 3 · Close the loop\nOnly after sending', [X[5] - 60, 240], [220, 320], COLOR.input),
  doc({ id: 'trigger-cron', name: N.cron, type: 'n8n-nodes-base.scheduleTrigger', typeVersion: 1.2, position: [X[0], Y - 80],
    parameters: { rule: { interval: [{ field: 'hours', hoursInterval: 1, triggerAtMinute: 20 }] } } }, 'At minute 20'),
  doc({ id: 'trigger-manual', name: N.manual, type: 'n8n-nodes-base.manualTrigger', typeVersion: 1, position: [X[0], Y + 120],
    parameters: {} }, 'For tests'),
  doc({ id: 'pg-classify', name: N.classify, type: 'n8n-nodes-base.postgres', typeVersion: 2.6, position: [X[1], Y],
    credentials: PG, parameters: { operation: 'executeQuery', query: read('n8n/sql/classify_offers.sql'), options: {} } },
    'new → candidate / filtered_out'),
  doc({ id: 'pg-pending', name: N.pending, type: 'n8n-nodes-base.postgres', typeVersion: 2.6, position: [X[2], Y],
    credentials: PG, executeOnce: true, parameters: { operation: 'executeQuery', query: pendingSql, options: {} } },
    'Best score first'),
  doc({ id: 'code-format', name: N.format, type: 'n8n-nodes-base.code', typeVersion: 2, position: [X[3], Y],
    parameters: { mode: 'runOnceForAllItems', jsCode: formatCode } }, `≤ ${MAX_INDIVIDUAL}: one each · else digest`),
  doc({ id: 'tg-send', name: N.send, type: 'n8n-nodes-base.telegram', typeVersion: 1.2, position: [X[4], Y],
    credentials: TG,
    parameters: { chatId: CHAT_ID, text: '={{ $json.text }}',
      additionalFields: { parse_mode: 'HTML', disable_web_page_preview: true, appendAttribution: false } } }, 'HTML, no previews'),
  doc({ id: 'pg-mark', name: N.mark, type: 'n8n-nodes-base.postgres', typeVersion: 2.6, position: [X[5], Y],
    credentials: PG, executeOnce: true,
    parameters: { operation: 'executeQuery', query: markSql,
      options: { queryReplacement: `={{ [ JSON.stringify($('${N.format}').all().flatMap((i) => i.json.ids)) ] }}` } } },
    'Sets notified_at'),
];

const { connections, link } = connector();
link(N.cron, N.classify);
link(N.manual, N.classify);
link(N.classify, N.pending);
link(N.pending, N.format);
link(N.format, N.send);
link(N.send, N.mark);

writeWorkflow('n8n/workflows/wf2-filtro-avisos.json', { id: 'taJY42QX0FhEhUse', name: 'WF2 · Filter & notify (Telegram)',
  nodes, connections, settings: { executionOrder: 'v1', timezone: 'America/Bogota' }, pinData: {}, active: false });
