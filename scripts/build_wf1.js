#!/usr/bin/env node
// Genera n8n/workflows/wf1-recoleccion.json a partir de:
//   scripts/normalizers/<fuente>.js  (código probado con node --test)
//   n8n/sql/upsert_offers.sql
// Uso: node scripts/build_wf1.js  →  luego importar (ver docs/INFRA.md)
'use strict';
const { read, COLOR, sticky, doc, connector, writeWorkflow } = require('./lib/wf');

const UA = 'Mozilla/5.0 (X11; Linux x86_64) job-hunter/0.1';
const PG_CRED = { postgres: { id: 'jhPgJobs00000001', name: 'Postgres jobs' } };

// Fuentes. Remotive pide ≤4 consultas/día → el cron va cada 6 h.
const SOURCES = [
  { key: 'remoteok', label: 'RemoteOK', fn: 'normalizeRemoteok', url: 'https://remoteok.com/api' },
  { key: 'remotive', label: 'Remotive', fn: 'normalizeRemotive', url: 'https://remotive.com/api/remote-jobs?category=software-dev' },
  { key: 'wwr', label: 'We Work Remotely', fn: 'normalizeWwr', url: 'https://weworkremotely.com/remote-jobs.rss' },
  { key: 'n8nforum', label: 'n8n Forum', fn: 'normalizeN8nforum', url: 'https://community.n8n.io/c/jobs/13.rss' },
  {
    // Varias URLs (categorías × páginas): un nodo previo emite un item por URL. Páginas de más devuelven [].
    key: 'getonbrd', label: 'GetOnBrd', fn: 'normalizeGetonbrd',
    urls: [['programming', 4], ['machine-learning-ai', 2], ['sysadmin-devops-qa', 3]].flatMap(([cat, pages]) =>
      Array.from({ length: pages }, (_, i) =>
        `https://www.getonbrd.com/api/v0/categories/${cat}/jobs?per_page=100&page=${i + 1}` +
        `&expand=${encodeURIComponent('["company","tags","seniority","modality","location_tenants","location_regions"]')}`)),
  },
];

const sql = read('n8n/sql/upsert_offers.sql');
const { connections, link } = connector();
const nodes = [];

// Layout: una fila por fuente; columnas = etapas.
const X = { trigger: 0, urls: 260, download: 500, normalize: 760, save: 1020 };
const Y0 = 320, ROW = 240;
const rows = SOURCES.length;
const mid = Y0 + ((rows - 1) * ROW) / 2;
const TRIGGER = 'Every 6 hours', MANUAL = 'Run manually';

nodes.push(
  sticky('header', [
    '## WF1 · Collect remote job offers',
    'Every 6 h downloads offers from **5 sources** (3 APIs, 2 RSS), normalizes them to one schema and **upserts** them',
    'into PostgreSQL (`offers`). Each source is an independent branch: one failing never stops the others.',
    '',
    '⚙️ Generated by `scripts/build_wf1.js` from tested code in `scripts/normalizers/` — **do not edit here**.',
  ].join('\n'), [-60, 0], [1300, 200], COLOR.header),
  sticky('triggers', '### Trigger\nCron every 6 h\n(Remotive allows ≤ 4 calls/day)', [-60, 240], [200, rows * ROW + 40], COLOR.trigger),
  sticky('download', '### 1 · Download\nHTTP GET, raw text response.\nRetries ×2 · continue on error', [X.urls - 60, 240], [X.download - X.urls + 200, rows * ROW + 40], COLOR.input),
  sticky('normalize', '### 2 · Normalize\nSource format → common schema.\nBad records are skipped.', [X.normalize - 60, 240], [240, rows * ROW + 40], COLOR.transform),
  sticky('save', '### 3 · Save\nIdempotent upsert by\n`(source, source_id)`', [X.save - 60, 240], [240, rows * ROW + 40], COLOR.output),
  doc({ id: 'trigger-cron', name: TRIGGER, type: 'n8n-nodes-base.scheduleTrigger', typeVersion: 1.2,
    position: [X.trigger, mid - 100], parameters: { rule: { interval: [{ field: 'hours', hoursInterval: 6 }] } } },
    'Runs all sources in parallel'),
  doc({ id: 'trigger-manual', name: MANUAL, type: 'n8n-nodes-base.manualTrigger', typeVersion: 1,
    position: [X.trigger, mid + 100], parameters: {} }, 'For tests'),
);

SOURCES.forEach((s, i) => {
  const y = Y0 + i * ROW;
  const multi = Array.isArray(s.urls);
  const urlsNode = `Build ${s.label} URLs`;
  const http = `Download ${s.label}`;
  const code = `Normalize ${s.label}`;
  const save = `Save ${s.label}`;
  const normalizer = read(`scripts/normalizers/${s.key}.js`)
    // Quita el export (una línea o bloque {…}): en n8n no existe module.
    .replace(/^if \(typeof module !== 'undefined'\)\s*(\{[\s\S]*?\n\}|[^\n]*)\s*$/m, '');
  if (/module\.exports/.test(normalizer)) throw new Error(`No se pudo quitar module.exports de ${s.key}.js`);

  if (multi) {
    nodes.push(doc({
      id: `urls-${s.key}`, name: urlsNode, type: 'n8n-nodes-base.code', typeVersion: 2,
      position: [X.urls, y],
      parameters: { mode: 'runOnceForAllItems', jsCode: `// One item per URL (categories × pages). Extra pages return [].\nreturn ${JSON.stringify(s.urls)}.map((url) => ({ json: { url } }));\n` },
    }, `${s.urls.length} URLs (categories × pages)`));
  }
  nodes.push(doc({
    id: `http-${s.key}`, name: http, type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2,
    position: [X.download, y], onError: 'continueRegularOutput', retryOnFail: true, maxTries: 2,
    parameters: {
      url: multi ? '={{ $json.url }}' : s.url,
      sendHeaders: true,
      headerParameters: { parameters: [{ name: 'User-Agent', value: UA }] },
      options: {
        timeout: 30000,
        ...(multi && { batching: { batch: { batchSize: 1, batchInterval: 1500 } } }), // amable con la API
        response: { response: { responseFormat: 'text', outputPropertyName: 'data' } },
      },
    },
  }, multi ? '1 request / 1.5 s (polite)' : (s.url.endsWith('.rss') ? 'RSS feed' : 'JSON API')));
  nodes.push(doc({
    id: `code-${s.key}`, name: code, type: 'n8n-nodes-base.code', typeVersion: 2,
    position: [X.normalize, y],
    parameters: {
      mode: 'runOnceForAllItems',
      jsCode: `// GENERATED by scripts/build_wf1.js from scripts/normalizers/${s.key}.js (unit-tested) — do not edit here.\n` +
        `${normalizer}\n` +
        `// Merge all responses (one per URL) and dedupe by source_id (the upsert rejects repeated keys).\n` +
        `const seen = new Set();\n` +
        `const offers = $input.all().flatMap((it) => {\n` +
        `  const body = it.json?.data ?? '';\n` +
        `  return ${s.fn}(typeof body === 'string' ? body : JSON.stringify(body));\n` +
        `}).filter((o) => !seen.has(o.source_id) && seen.add(o.source_id));\n` +
        `return [{ json: { source: '${s.key}', count: offers.length, payload: JSON.stringify(offers) } }];\n`,
    },
  }, `${s.fn}() + dedupe`));
  nodes.push(doc({
    id: `pg-${s.key}`, name: save, type: 'n8n-nodes-base.postgres', typeVersion: 2.6,
    position: [X.save, y], credentials: PG_CRED,
    parameters: { operation: 'executeQuery', query: sql, options: { queryReplacement: '={{ [ $json.payload ] }}' } },
  }, 'Upsert → new / total'));

  const first = multi ? urlsNode : http;
  link(TRIGGER, first);
  link(MANUAL, first);
  if (multi) link(urlsNode, http);
  link(http, code);
  link(code, save);
});

writeWorkflow('n8n/workflows/wf1-recoleccion.json', {
  id: 'jhWf1Recoleccion',
  name: 'WF1 · Collect job offers',
  nodes,
  connections,
  settings: { executionOrder: 'v1', timezone: 'America/Bogota' },
  pinData: {},
  active: false,
});
